#!/usr/bin/env bash
# palette.sh - Extract a dynamic color palette from a wallpaper image
# Usage: palette.sh <image_path>
# Outputs: JSON palette to ~/.config/quickshell/palette.json + stdout
set -e

IMAGE="$1"
OUTPUT="$HOME/.config/quickshell/palette.json"

if [ -z "$IMAGE" ] || [ ! -f "$IMAGE" ]; then
    echo "Usage: $0 <image_path>" >&2
    exit 1
fi

python3 -c "
import os, colorsys, json
from PIL import Image
import numpy as np
from scipy.cluster.vq import kmeans

Image.MAX_IMAGE_PIXELS = None

def extract_palette(image_path):
    img = Image.open(image_path).convert('RGB')
    img.thumbnail((150, 150))
    pixels = np.array(img).reshape(-1, 3).astype(float)
    try:
        centroids, _ = kmeans(pixels, 8)
    except Exception:
        centroids = pixels[:8]
    colors = []
    for c in centroids:
        r, g, b = c / 255.0
        h, l, s = colorsys.rgb_to_hls(r, g, b)
        colors.append({'rgb': (int(c[0]), int(c[1]), int(c[2])), 'h': h, 'l': l, 's': s})

    def accent_score(c):
        s, l = c['s'], c['l']
        if l < 0.20 or l > 0.88:
            return -1
        return s * (1.0 - abs(l - 0.55))

    sorted_colors = sorted(colors, key=accent_score, reverse=True)
    if sorted_colors and sorted_colors[0]['s'] > 0.10:
        best = sorted_colors[0]
    else:
        best = {'h': 0.75, 'l': 0.70, 's': 0.70}

    ah, al, asat = best['h'], best['l'], best['s']
    accent_h = ah
    accent_s = min(max(asat, 0.55), 0.88)
    accent_l = min(max(al, 0.64), 0.79)
    ar, ag, ab = colorsys.hls_to_rgb(accent_h, accent_l, accent_s)
    accent_hex = '#{:02x}{:02x}{:02x}'.format(int(ar*255), int(ag*255), int(ab*255))

    def dark(l, sat_mult=0.14):
        r, g, b = colorsys.hls_to_rgb(accent_h, l, min(accent_s * sat_mult, 0.13))
        return '#{:02x}{:02x}{:02x}'.format(int(r*255), int(g*255), int(b*255))

    def light_text(l, sat_mult=0.10):
        r, g, b = colorsys.hls_to_rgb(accent_h, l, min(accent_s * sat_mult, 0.09))
        return '#{:02x}{:02x}{:02x}'.format(int(r*255), int(g*255), int(b*255))

    return {
        'mantle':   dark(0.08, 0.12),
        'base':     dark(0.12, 0.14),
        'surface0': dark(0.18, 0.16),
        'surface1': dark(0.25, 0.20),
        'text':     light_text(0.91, 0.09),
        'subtext0': light_text(0.73, 0.11),
        'subtext1': light_text(0.82, 0.10),
        'mauve':    accent_hex,
        'red':      '#f38ba8',
    }

palette = extract_palette('$IMAGE')
output_path = os.path.expanduser('$OUTPUT')
with open(output_path, 'w') as f:
    json.dump(palette, f, indent=2)

vesktop_css_dir = os.path.expanduser('~/.config/vesktop/settings')
if os.path.isdir(vesktop_css_dir):
    vesktop_css_path = os.path.join(vesktop_css_dir, 'wallpaper-palette.css')
    css_content = f'''/* Auto-generated by quickshell wallpaper palette */
:root {{
    --bg-4: {palette['mantle']} !important;
    --bg-3: {palette['base']} !important;
    --bg-2: {palette['surface0']} !important;
    --bg-1: {palette['surface1']} !important;
    --text-1: {palette['text']} !important;
    --text-2: {palette['subtext1']} !important;
    --text-3: {palette['subtext0']} !important;
    --accent-1: {palette['mauve']} !important;
    --accent-2: {palette['mauve']} !important;
    --accent-3: {palette['mauve']} !important;
    --accent-4: {palette['mauve']} !important;
    --accent-5: {palette['mauve']} !important;
    --brand-experiment: {palette['mauve']} !important;
}}
'''
    with open(vesktop_css_path, 'w') as f:
        f.write(css_content)

print(json.dumps(palette))
"
